// Builders of the manifests and lock files the dependency tests write (test/unit/facts-deps-*.test.mjs and
// facts-network-*.test.mjs): one place for the hosts, the special characters and each format's shape, so that a test
// says what differs from an ordinary file and nothing else. Each builder writes the file as its tool does (key order,
// quoting, indentation); a test that needs a form no tool writes spells that part out itself.

/** The registries and indexes the tests name: the public ones, and a company's own. */
export const HOST = Object.freeze({
  npm: "https://registry.npmjs.org",
  yarn: "https://registry.yarnpkg.com",
  corpNpm: "https://npm.corp.internal",
  pypi: "https://pypi.org/simple",
  corpPypi: "https://pypi.corp.internal/simple",
  pyFiles: "https://files.pythonhosted.org/packages",
  corpFiles: "https://files.corp.internal/packages",
  corpGit: "https://git.corp.internal",
});

/** Characters a test writes in a file without Prettier or an editor turning them into something else. */
export const CH = Object.freeze({
  BACKSLASH: String.fromCharCode(92),
  CR: String.fromCharCode(13),
  LS: String.fromCharCode(0x2028),
  BOM: String.fromCharCode(0xfeff),
  NUL: String.fromCharCode(0),
});

/** An npm tarball URL as a registry gives it: `<host>/<name>/-/<base>-<version>.tgz`. */
export const tarball = (name, { host = HOST.npm, version = "1.0.0" } = {}) =>
  `${host}/${name}/-/${name.split("/").pop()}-${version}.tgz`;

/**
 * The URL `--network` requests for a package, its latest version's document: npm's (its name encoded as npm's
 * registry wants it), PyPI's.
 */
export const registryUrl = (ecosystem, name) =>
  ecosystem === "npm" ? `${HOST.npm}/${encodeURIComponent(name)}/latest` : `https://pypi.org/pypi/${name}/json`;

/** A package.json: its dependencies and devDependencies, as `{ name: range }`. */
export const packageJson = (dependencies = {}, devDependencies = {}, rest = {}) => ({
  name: "app",
  version: "1.0.0",
  ...(Object.keys(dependencies).length ? { dependencies } : {}),
  ...(Object.keys(devDependencies).length ? { devDependencies } : {}),
  ...rest,
});

/** One package-lock v2/v3 entry taken from a registry: its version and its own tarball there (`host` to change it). */
export const npmEntry = (name, { version = "1.0.0", host = HOST.npm, ...rest } = {}) => ({
  version,
  resolved: tarball(name, { host, version }),
  integrity: "sha512-AAAA",
  ...rest,
});

/**
 * A package-lock.json v3: its root entry declares `root` (`{ name: range }`), then the entries `{ location: entry }`.
 * `version` 2 writes the same `packages`.
 */
export const packageLockV3 = (root, entries = {}, { version = 3 } = {}) => ({
  name: "app",
  version: "1.0.0",
  lockfileVersion: version,
  requires: true,
  packages: { "": { name: "app", version: "1.0.0", dependencies: root }, ...entries },
});

/** One package-lock v1 dependency taken from a registry, with its nested ones (`dependencies`) if any. */
export const v1Entry = (name, { version = "1.0.0", host = HOST.npm, ...rest } = {}) => ({
  version,
  resolved: tarball(name, { host, version }),
  integrity: "sha512-AAAA",
  ...rest,
});

/** A package-lock.json v1: its nested `dependencies` tree, `{ name: entry }`. */
export const packageLockV1 = (dependencies) => ({
  name: "app",
  version: "1.0.0",
  lockfileVersion: 1,
  requires: true,
  dependencies,
});

/**
 * One yarn.lock v1 block as Yarn 1 writes it: its header (`lodash@^4.17.21`, several joined by ", ", quoted when Yarn
 * quotes them), its version, its `resolved` (the package's own tarball on Yarn's registry unless given), its integrity
 * and its dependencies (`{ name: range }`).
 */
export function yarnBlock(header, { name, version = "1.0.0", resolved, integrity = "sha512-AAAA", dependencies } = {}) {
  const pkg = name ?? header.replace(/^"/, "").replace(/@[^@]*$/, "");
  const lines = [
    `${header}:`,
    `  version "${version}"`,
    `  resolved "${resolved ?? `${tarball(pkg, { host: HOST.yarn, version })}#0000000000000000000000000000000000000000`}"`,
    `  integrity ${integrity}`,
  ];
  if (dependencies && Object.keys(dependencies).length) {
    lines.push("  dependencies:");
    for (const [dep, range] of Object.entries(dependencies)) lines.push(`    ${dep} "${range}"`);
  }
  return `${lines.join("\n")}\n`;
}

/** A yarn.lock v1: Yarn 1's header comment, then its blocks, a blank line between them. */
export const yarnLock = (...blocks) =>
  `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n${blocks.join("\n")}`;

/** A pyproject.toml declaring PEP 621 `[project]` dependencies (PEP 508 strings), then whatever `rest` holds. */
export const pyproject = (dependencies = [], rest = "", { name = "app" } = {}) =>
  `[project]\nname = "${name}"\nversion = "0.1.0"\ndependencies = [${dependencies.map((d) => JSON.stringify(d)).join(", ")}]\n${rest ? `\n${rest}` : ""}`;

/** A pyproject.toml declaring Poetry's `[tool.poetry.dependencies]` (`{ name: constraint }`), then `rest`. */
export const poetryProject = (dependencies = {}, rest = "") =>
  `[tool.poetry]\nname = "app"\nversion = "0.1.0"\n\n[tool.poetry.dependencies]\npython = "^3.11"\n${Object.entries(
    dependencies,
  )
    .map(([n, c]) => `${n} = ${JSON.stringify(c)}`)
    .join("\n")}\n${rest ? `\n${rest}` : ""}`;

/**
 * One uv.lock `[[package]]` block as uv writes it: its name, version and source (PyPI's registry unless given), its
 * files on PyPI's file host (`sdist`), its dependencies (`[{ name }]`), and `rest` (more lines, as written).
 */
export function uvPackage(
  name,
  { version = "1.0.0", registry = HOST.pypi, source, files = true, dependencies = [], rest = "" } = {},
) {
  const lines = [
    "[[package]]",
    `name = "${name}"`,
    `version = "${version}"`,
    `source = ${source ?? `{ registry = "${registry}" }`}`,
  ];
  if (dependencies.length) lines.push(`dependencies = [${dependencies.map((d) => `{ name = "${d}" }`).join(", ")}]`);
  if (files && !source)
    lines.push(
      `sdist = { url = "${HOST.pyFiles}/ab/cd/${name.replace(/-/g, "_")}-${version}.tar.gz", hash = "sha256:00" }`,
    );
  return `${lines.join("\n")}\n${rest}`;
}

/** A uv.lock: its version line, then its blocks, a blank line between them. */
export const uvLock = (...packages) => `version = 1\nrequires-python = ">=3.11"\n\n${packages.join("\n")}`;

/**
 * One poetry.lock `[[package]]` block as Poetry writes it: its name and version, its files, and — a package taken
 * elsewhere than PyPI — its `[package.source]` (`{ type, url, reference }`), then `rest`.
 */
export function poetryPackage(name, { version = "1.0.0", source, rest = "" } = {}) {
  const lines = [
    "[[package]]",
    `name = "${name}"`,
    `version = "${version}"`,
    'description = ""',
    "optional = false",
    'python-versions = ">=3.8"',
    'files = [{ file = "x.tar.gz", hash = "sha256:00" }]',
  ];
  let text = `${lines.join("\n")}\n${rest}`;
  if (source)
    text += `\n[package.source]\n${Object.entries(source)
      .map(([k, v]) => `${k} = ${JSON.stringify(v)}`)
      .join("\n")}\n`;
  return text;
}

/** A poetry.lock: its blocks, then its `[metadata]`. */
export const poetryLock = (...packages) =>
  `${packages.join("\n")}\n[metadata]\nlock-version = "2.0"\npython-versions = "^3.11"\ncontent-hash = "00"\n`;
